import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {analysisTotals,selectResults} from '../web/model.mjs';
const snapshot=JSON.parse(await readFile(new URL('../docs/analysis-probe-summary.json',import.meta.url)));
const all=analysisTotals(snapshot.results);
assert.equal(all.records,40);
assert.equal(all.skills.find(s=>s.id==='sql').count,3);
assert.equal(all.locations.unknown,39);
assert.equal(analysisTotals(selectResults(snapshot,'himalayas')).records,20);
assert.equal(analysisTotals([{http_status:200,sample_records:20}]),null);
const broken=structuredClone(snapshot.results);
broken[0].analysis.skill_mention_counts.sql=999;
assert.equal(analysisTotals(broken).records,20);
assert.equal(analysisTotals(broken).partial,true);
broken[1].analysis.location_signal_counts.unknown=-1;
assert.equal(analysisTotals(broken),null);
const failed=structuredClone(snapshot.results);
failed[0].http_status=500;
assert.equal(analysisTotals(failed).records,20);
console.log('PASS analysis aggregation, filtering, missing, invalid and failed data');
const {skillsForCareer}=await import('../web/model.mjs');
assert.equal(skillsForCareer(all,'data_analyst').length,5);
assert.equal(skillsForCareer(all,'digital_marketer').find(s=>s.id==='ga4').count,0);
assert.equal(skillsForCareer(all,'graphic_designer').some(s=>s.id==='sql'),false);
assert.deepEqual(skillsForCareer(all,'invalid'),[]);
assert.deepEqual(skillsForCareer(null),[]);
assert.equal(all.records,40);
console.log('PASS career vocabulary filters, zero counts and unchanged denominator');


const v2=structuredClone(snapshot.results);
for(const row of v2)row.analysis.method_version='editorial-mentions-v2';
assert.equal(analysisTotals(v2).records,40);
assert.equal(analysisTotals(v2).methodVersion,'editorial-mentions-v2');
const mixed=structuredClone(v2);
mixed[0].analysis.method_version='editorial-mentions-v1';
assert.equal(analysisTotals(mixed),null);
assert.equal(analysisTotals([mixed[0]]).methodVersion,'editorial-mentions-v1');
assert.equal(analysisTotals([mixed[1]]).methodVersion,'editorial-mentions-v2');
const future=structuredClone(v2);
for(const row of future)row.analysis.method_version='editorial-mentions-v999';
assert.equal(analysisTotals(future),null);
console.log('PASS v2 aggregates, mixed-method refusal, source isolation and unknown versions');
